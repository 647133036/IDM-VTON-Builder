let current = 'zh'
try {
  current = localStorage.getItem(LANG_KEY) || 'zh'
} catch {}

export function t(key, vars) {
  const entry = messages[current]
  let text = (entry && entry[key]) || key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v))
    }
  }
  return text
}

export function getLang() {
  return current
}

export function setLang(lang) {
  current = lang === 'en' ? 'en' : 'zh'
  try {
    localStorage.setItem(LANG_KEY, current)
  } catch {}
}

export function fmtAudience(key) {
  return t(`aud.${key}`) || key
}

export function fmtAge(key) {
  return t(`age.${key}`) || key
}

export function fmtEthnicity(value, fallback) {
  const key = `eth.${value}`
  const translated = t(key)
  return translated && translated !== key ? translated : (fallback || value || '')
}